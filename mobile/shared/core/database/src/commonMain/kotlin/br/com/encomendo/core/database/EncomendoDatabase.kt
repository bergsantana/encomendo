package br.com.encomendo.core.database

import androidx.room3.AutoMigration
import androidx.room3.ConstructedBy
import androidx.room3.Database
import androidx.room3.RoomDatabase
import androidx.room3.RoomDatabaseConstructor
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import kotlin.coroutines.CoroutineContext

/**
 * The offline cache of the management app (Room 3, see docs/adr/0005-room3-and-agp9.md).
 *
 * It holds copies of server data for weak-signal workshops plus the offline
 * write queue. The server stays the source of truth: anything here can be
 * dropped and fetched again.
 */
@Database(
    entities = [SyncStateEntity::class, CatalogPageEntity::class, CatalogDetailEntity::class],
    version = 2,
    exportSchema = true,
    // 1 -> 2 adds the catalog cache tables and changes nothing else.
    autoMigrations = [AutoMigration(from = 1, to = 2)],
)
@ConstructedBy(EncomendoDatabaseConstructor::class)
abstract class EncomendoDatabase : RoomDatabase() {
    /** Returns the DAO that records when each cached collection was last refreshed. */
    abstract fun syncStateDao(): SyncStateDao

    /** Returns the DAO of the cached catalog list pages (items, kits, categories, fields, suppliers). */
    abstract fun catalogPageDao(): CatalogPageDao

    /** Returns the DAO of the cached catalog details (an item, kit or supplier). */
    abstract fun catalogDetailDao(): CatalogDetailDao
}

/** Generated by Room's KSP processor for each platform. */
@Suppress("KotlinNoActualForExpect")
expect object EncomendoDatabaseConstructor : RoomDatabaseConstructor<EncomendoDatabase> {
    override fun initialize(): EncomendoDatabase
}

/**
 * Builds the database from a platform builder with the bundled SQLite driver,
 * so behavior is the same on every device and platform.
 *
 * @param queryContext where queries run; injected so tests can use a test dispatcher.
 */
fun buildDatabase(
    builder: RoomDatabase.Builder<EncomendoDatabase>,
    queryContext: CoroutineContext,
): EncomendoDatabase =
    builder
        .setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(queryContext)
        .build()
